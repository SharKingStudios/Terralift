#!/usr/bin/env python3
"""Generate the static room-and-corridor map used by Nav2.

The listed rectangles are the *only* permanently traversable areas.  They
match the physical walls in ``worlds/spatial_warehouse.sdf``: five enclosed
rooms joined by five deliberate corridors, with no alternate shortcut through
the surrounding building space. Dynamic passage barriers are omitted so the
live LiDAR obstacle layers can represent a close or re-open event.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET


RESOLUTION = 0.05
ORIGIN_X, ORIGIN_Y = -24.0, -20.0
WIDTH, HEIGHT = 960, 800


def world_to_pixel(x: float, y: float) -> tuple[int, int]:
    return int((x - ORIGIN_X) / RESOLUTION), int((y - ORIGIN_Y) / RESOLUTION)


def fill_rect(grid: list[list[int]], minimum_x: float, maximum_x: float, minimum_y: float, maximum_y: float, value: int) -> None:
    left, bottom = world_to_pixel(minimum_x, minimum_y)
    right, top = world_to_pixel(maximum_x, maximum_y)
    for y in range(max(0, bottom), min(HEIGHT, top + 1)):
        for x in range(max(0, left), min(WIDTH, right + 1)):
            grid[y][x] = value


# The physical floor plan follows the study diagram: A/B at the left, a tall
# central C, D at the right, and E low in the centre.  The two right-hand
# links are L-shaped. Every free rectangle belongs either to one room or one
# declared two-room passage; there are no unmodelled shortcuts.
FREE_REGIONS = (
    (-18.7, -11.3, -13.6, -6.4),  # A: lower-left room
    (-18.7, -11.3, 0.4, 7.6),     # B: upper-left room
    (-6.3, 2.3, 0.0, 14.0),       # C: deliberately taller central room
    (11.3, 18.7, 0.4, 7.6),       # D: upper-right room
    (-6.3, 2.3, -13.6, -6.4),     # E: lower-central room
    (-16.2, -13.8, -6.4, 0.4),    # A <-> B, vertical
    (-11.3, -6.3, 2.8, 5.2),      # B <-> C, horizontal
    (2.3, 16.2, 10.8, 13.2),      # C <-> D, horizontal leg
    (13.8, 16.2, 7.6, 13.2),      # C <-> D, downward leg
    (13.8, 16.2, -8.0, 0.4),      # D <-> E, downward leg
    (2.3, 16.2, -9.2, -6.8),      # D <-> E, leftward leg
    (-11.3, -6.3, -11.2, -8.8),   # E <-> A, red horizontal link
)


def permanent_wall_rectangles() -> list[tuple[float, float, float, float]]:
    """Return the permanent Gazebo wall footprints in world coordinates.

    The static Nav2 map intentionally comes from the same SDF collision
    geometry that constrains the robot.  It therefore excludes permanent
    walls while retaining the declared door openings and all dynamic-passage
    space.  Dynamic blockers are deliberately *not* part of this map: they
    must be discovered through live LiDAR.
    """
    world_path = Path(__file__).parents[1] / "worlds" / "spatial_warehouse.sdf"
    world = ET.parse(world_path).getroot()
    wall_model = world.find("./world/model[@name='black_walls']")
    if wall_model is None:
        raise RuntimeError(f"Could not find permanent wall model in {world_path}")

    rectangles = []
    for link in wall_model.findall("./link"):
        link_pose = link.findtext("pose")
        if not link_pose:
            raise RuntimeError(f"Permanent wall link {link.attrib.get('name')} has no pose")
        link_x, link_y, *_ = map(float, link_pose.split())
        for collision in link.findall("collision"):
            size = collision.findtext("geometry/box/size")
            if not size:
                raise RuntimeError(f"Permanent wall collision {collision.attrib.get('name')} is not a box")
            sx, sy, _ = map(float, size.split())
            collision_pose = collision.findtext("pose")
            if collision_pose:
                offset_x, offset_y, *_ = map(float, collision_pose.split())
            else:
                offset_x = offset_y = 0.0
            x, y = link_x + offset_x, link_y + offset_y
            rectangles.append((x - sx / 2, x + sx / 2, y - sy / 2, y + sy / 2))
    return rectangles


def write_map(pgm_path: Path, yaml_path: Path) -> None:
    # 254 is Nav2 free, 0 is occupied. Begin occupied, then carve only the
    # physical building floor plan. P2 is intentionally portable/readable.
    grid = [[0 for _ in range(WIDTH)] for _ in range(HEIGHT)]
    for region in FREE_REGIONS:
        fill_rect(grid, *region, value=254)
    for wall in permanent_wall_rectangles():
        fill_rect(grid, *wall, value=0)
    pgm_path.parent.mkdir(parents=True, exist_ok=True)
    with pgm_path.open("w", encoding="ascii") as stream:
        stream.write(f"P2\n# generated by Terralift\n{WIDTH} {HEIGHT}\n255\n")
        # Image rows begin at top, while the grid origin is at bottom.
        for row in reversed(grid):
            stream.write(" ".join(map(str, row)) + "\n")
    yaml_path.write_text(
        "image: " + pgm_path.name + "\n"
        f"resolution: {RESOLUTION}\norigin: [{ORIGIN_X}, {ORIGIN_Y}, 0.0]\n"
        "negate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.25\n",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path, help="Output .pgm path")
    parser.add_argument("--yaml-output", type=Path, help="Output map YAML; defaults beside PGM")
    args = parser.parse_args()
    write_map(args.output, args.yaml_output or args.output.with_suffix(".yaml"))


if __name__ == "__main__":
    main()
